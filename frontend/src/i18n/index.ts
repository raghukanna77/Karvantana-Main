export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
  fallback?: string,
): string {
  const dict = catalogs[lang] ?? en
  let text = dict[key] ?? en[key] ?? fallback ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v))
  }
  return text
}

export function catalogNote(lang: Lang): string | undefined {
  return regionalNotes[lang]
}

/** React hook: `const { t, lang } = useT()` — re-renders on language change. */
export function useT() {
  const lang = useUi((s) => s.lang)
  const t = useCallback(
    (key: string, vars?: Record<string, string | number>, fallback?: string) =>
      translate(lang, key, vars, fallback),
    [lang],
  )
  return { lang, t }
}

/** Persist the chosen language server-side (best-effort; local store always wins offline). */
export function persistLanguage(lang: Lang): void {
  if (useAuth.getState().user) {
    void api.patch('/auth/me', { preferred_language: lang }).catch(() => {})
  }
}

/** Order status → translated human label (server's status_label is the English fallback). */
const STATUS_KEYS: Record<string, string> = {
  DRAFT: 'order.draft',
  PENDING_PAYMENT: 'order.awaiting_payment',
  CONFIRMED: 'order.confirmed',
  PROCESSING: 'order.processing',
  IN_PRODUCTION: 'order.in_production',
  READY_TO_SHIP: 'order.ready_to_ship',
  SHIPPED: 'order.shipped',
  DELIVERED: 'order.delivered',
  COMPLETED: 'order.completed',
  CANCELLED: 'order.cancelled',
  REFUNDED: 'order.refunded',
}

export function useStatusLabel() {
  const { t } = useT()
  return useCallback(
    (status: string, serverLabel?: string | null) => {
      const key = STATUS_KEYS[status]
      return key ? t(key) : (serverLabel ?? status.replace(/_/g, ' ').toLowerCase())
    },
    [t],
  )
}
